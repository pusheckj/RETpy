def get_statistics():
    """Calculate and return statistics for historical returns."""
    import numpy as np
    return {
        'years': len(YEARS),
        'year_range': (YEARS[0], YEARS[-1]),
        'stock_mean': np.mean(STOCK_RETURNS),
        'stock_std': np.std(STOCK_RETURNS),
        'stock_min': min(STOCK_RETURNS),
        'stock_min_year': YEARS[STOCK_RETURNS.index(min(STOCK_RETURNS))],
        'stock_max': max(STOCK_RETURNS),
        'stock_max_year': YEARS[STOCK_RETURNS.index(max(STOCK_RETURNS))],
        'bond_mean': np.mean(BOND_RETURNS),
        'bond_std': np.std(BOND_RETURNS),
    }


